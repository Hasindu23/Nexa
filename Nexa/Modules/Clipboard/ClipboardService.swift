import AppKit
import Combine

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, url, image, files }
    let id: UUID
    let kind: Kind
    let text: String
    let data: Data?
    let createdAt: Date
    var pinned = false
    var title: String { kind == .image ? "Copied image" : text.replacingOccurrences(of: "\n", with: " ") }
}

@MainActor final class ClipboardService: ObservableObject, ModuleLifecycle {
    @Published private(set) var items: [ClipItem] = []
    @Published var paused = false
    @Published var error: String?
    private let store: LocalStore
    private let pasteboard: NSPasteboard
    private var poller: Timer?
    private var lastChange: Int
    var limit = 80
    var onCopy: (() -> Void)?
    static let maxPayload = 4 * 1024 * 1024
    static let sensitiveTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "com.apple.is-remote-clipboard"]
    init(store: LocalStore, pasteboard: NSPasteboard = .general) {
        self.store = store; self.pasteboard = pasteboard; lastChange = pasteboard.changeCount
        items = store.read([ClipItem].self, name: "clipboard.json") ?? []
    }
    func start() {
        guard poller == nil else { return }
        lastChange = pasteboard.changeCount
        let timer = Timer(timeInterval: 1.5, repeats: true) { [weak self] _ in Task { @MainActor in self?.capture() } }
        timer.tolerance = 0.5; RunLoop.main.add(timer, forMode: .common); poller = timer
    }
    func stop() { poller?.invalidate(); poller = nil; lastChange = pasteboard.changeCount }
    func capture() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard !paused, !Self.sensitiveTypes.contains(where: { pasteboard.types?.contains(NSPasteboard.PasteboardType($0)) == true }) else { return }
        let types = pasteboard.types ?? []
        let item: ClipItem
        if types.contains(.fileURL), let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            item = ClipItem(id: UUID(), kind: .files, text: urls.map(\.absoluteString).joined(separator: "\n"), data: nil, createdAt: Date())
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty, text.utf8.count <= Self.maxPayload {
            let scheme = URL(string: text)?.scheme?.lowercased()
            item = ClipItem(id: UUID(), kind: scheme == "https" || scheme == "http" ? .url : .text, text: text, data: nil, createdAt: Date())
        } else if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), data.count <= Self.maxPayload {
            item = ClipItem(id: UUID(), kind: .image, text: "Image", data: data, createdAt: Date())
        } else { return }
        insert(item)
    }
    func insert(_ item: ClipItem) {
        let duplicate = items.first { $0.kind == item.kind && $0.text == item.text && $0.data == item.data }
        items.removeAll { $0.kind == item.kind && $0.text == item.text && $0.data == item.data }
        var value = item; value.pinned = duplicate?.pinned ?? item.pinned
        items.insert(value, at: 0); trim(); save()
    }
    func trim() {
        let capacity = max(10, min(500, limit))
        let pinned = items.filter(\.pinned)
        items = pinned + items.filter { !$0.pinned }.prefix(max(0, capacity - pinned.count))
        // Keep a bounded disk footprint even for a history containing only images.
        while items.reduce(0, { $0 + ($1.data?.count ?? $1.text.utf8.count) }) > 32 * 1024 * 1024 {
            guard let index = items.lastIndex(where: { !$0.pinned }) else { break }
            items.remove(at: index)
        }
        save()
    }
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        if item.kind == .image, let data = item.data, let image = NSImage(data: data) { pasteboard.writeObjects([image]) }
        else if item.kind == .files { pasteboard.writeObjects(item.text.components(separatedBy: "\n").compactMap(URL.init(string:)).map { $0 as NSURL }) }
        else { pasteboard.setString(item.text, forType: .string) }
        lastChange = pasteboard.changeCount; onCopy?()
    }
    func pin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        if !items[index].pinned && items.filter(\.pinned).count >= min(limit, 50) { error = "Unpin an item before pinning another."; return }
        items[index].pinned.toggle(); trim()
    }
    func delete(_ item: ClipItem) { items.removeAll { $0.id == item.id }; save() }
    func clear() { items.removeAll(); save() }
    private func save() {
        do { try store.write(items, name: "clipboard.json") }
        catch { self.error = "Clipboard history could not be saved." }
    }
}
